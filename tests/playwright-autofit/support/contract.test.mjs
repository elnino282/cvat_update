import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, writeFile, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { gzipSync } from 'node:zlib';
import { labels, runName, assertOwnedTask, resolveSchema, prerequisites, allowLocalSkip,
    toPCD, sha256, loadRealFixture } from './contract.mjs';

test('cleanup accepts only the exact runtime ID/name generated by this run', () => {
    const owned = { id: 481, name: runName('mocked') };
    assert.doesNotThrow(() => assertOwnedTask({ ...owned }, owned));
    assert.throws(() => assertOwnedTask({ ...owned, id: owned.id + 1 }, owned), /Refusing/);
    assert.throws(() => assertOwnedTask({ ...owned, name: runName('mocked') }, owned), /Refusing/);
    assert.throws(() => assertOwnedTask({ id: 481, name: 'user task' }, { id: 481, name: 'user task' }), /Refusing/);
});

test('runtime taxonomy IDs are resolved, with a single two-wheels label and no subtype', () => {
    const runtime = structuredClone(labels);
    runtime[0].id = 1425;
    runtime[0].attributes[0].id = 6208;
    assert.deepEqual(resolveSchema(runtime), { vehicleLabelId: 1425, typeAttributeId: 6208 });
    assert.deepEqual(labels.find((label) => label.name === 'two-wheels').attributes.map((attribute) => attribute.name), ['ride_state']);
    runtime[0].attributes[0].values.reverse();
    assert.throws(() => resolveSchema(runtime), /taxonomy/);
});

test('local skip is opt-in and cannot weaken CI or acceptance', () => {
    assert.equal(allowLocalSkip({}), false);
    assert.equal(allowLocalSkip({ AUTOFIT_ALLOW_LOCAL_SKIP: '1' }), true);
    assert.equal(allowLocalSkip({ AUTOFIT_ALLOW_LOCAL_SKIP: '1', CI: 'true' }), false);
    assert.equal(allowLocalSkip({ AUTOFIT_ALLOW_LOCAL_SKIP: '1', AUTOFIT_ACCEPTANCE: '1' }), false);
    assert.equal(prerequisites(false, {}).length, 2);
    assert.equal(prerequisites(true, {}).length, 5);
});

test('PCD conversion preserves XYZ float32 order and rejects non-finite input', () => {
    const pcd = toPCD([[1, 2, 3], [4, 5, 6]]);
    const dataOffset = pcd.indexOf('DATA binary\n') + Buffer.byteLength('DATA binary\n');
    assert.equal(pcd.readFloatLE(dataOffset + 12), 4);
    assert.equal(pcd.readFloatLE(dataOffset + 20), 6);
    assert.throws(() => toPCD([[NaN, 0, 0]]), /finite/);
});

test('locked real fixture verifies manifest/cloud hash, held-out split and seed index', async () => {
    const root = await mkdtemp(path.join(os.tmpdir(), 'autofit-pw-contract-'));
    try {
        const cloud = Buffer.alloc(40);
        [1, 2, 3, 0.5, 0, 4, 5, 6, 0.2, 0].forEach((value, index) => cloud.writeFloatLE(value, index * 4));
        await writeFile(path.join(root, 'lidar.bin'), cloud);
        const manifest = { frames: { sample: { lidar_path: 'lidar.bin', sha256: sha256(cloud), split: 'held_out', point_dimensions: 5 } },
            cases: [{ case_id: 'case', sample_token: 'sample', annotation_token: 'annotation',
                target_label: 'vehicles', vehicles_type: 'car', split: 'held_out', seeds: [{ pointIndex: 1, point: [4, 5, 6] }] }] };
        const compressed = gzipSync(JSON.stringify(manifest));
        const manifestPath = path.join(root, 'manifest.json.gz');
        await writeFile(manifestPath, compressed);
        const env = { AUTOFIT_MANIFEST: manifestPath, AUTOFIT_MANIFEST_SHA256: sha256(compressed), NUSCENES_DATAROOT: root };
        assert.equal((await loadRealFixture(env)).selected.case_id, 'case');
        await assert.rejects(() => loadRealFixture({ ...env, AUTOFIT_MANIFEST_SHA256: '0'.repeat(64) }), /Manifest SHA256/);
        await assert.rejects(() => loadRealFixture({ ...env, AUTOFIT_CASE_ID: 'missing' }), /no requested held-out Car/);
        await writeFile(path.join(root, 'lidar.bin'), Buffer.alloc(40));
        await assert.rejects(() => loadRealFixture(env), /hash\/stride/);
    } finally {
        await rm(root, { recursive: true, force: true });
    }
});
